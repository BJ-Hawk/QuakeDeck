const data = JSON.parse(readFileSync(path, 'utf8'));
let updated = 0;
for (const station of data.stations) {
  const placement = placements.get(station.nameJa);
  if (!placement || station.publishedAddressJa || station.facilityNameJa) continue;
  const [address, facility] = placement;
  station.publishedAddressJa = `長崎県${address}`;
  station.facilityNameJa = facility;
  station.metadataStatus = 'Official prefectural instrument placement list';
  station.note = 'Nagasaki Prefecture’s official earthquake-instrument placement dataset identifies the observation point, exact address, and host facility.';
  station.placementPrecision = 'exact_address';
  station.sourceUrls = [...new Set([...(station.sourceUrls ?? []), sourceUrl])];
  updated += 1;
}
writeFileSync(path, `${JSON.stringify(data, null, 2)}\n`, 'utf8');
