const data = JSON.parse(readFileSync(path, 'utf8'));
const stations = new Map(data.stations.map((station) => [station.code, station]));
for (const [code, address, facility] of updates) {
  const station = stations.get(code);
  if (!station || station.prefectureJa !== '青森県' || station.publishedAddressJa) throw new Error(`Refusing update for ${code}`);
  Object.assign(station, {
    publishedAddressJa: address,
    facilityNameJa: facility,
    placementPrecision: 'exact_address',
    metadataStatus: 'source_verified',
    note: "Verified against Aomori Prefecture's official seismic-intensity network register."
  });
  delete station.placementLocalityJa;
  station.sourceUrls = [...new Set([...(station.sourceUrls ?? []), source])];
}
data.coverage.publishedAddresses += updates.length;
data.coverage.exactPlacementAddressUpdates += updates.length;
data.coverage.localityPlacementRecords -= updates.length;
writeFileSync(path, `${JSON.stringify(data, null, 2)}\n`, 'utf8');
